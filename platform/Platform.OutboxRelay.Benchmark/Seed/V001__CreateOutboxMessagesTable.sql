-- Benchmark-only provisioning for the OutboxRelay throughput benchmark.
-- Applied to a throwaway PostgreSQL Testcontainer by Evolve (see PostgreSqlTestContainer);
-- Evolve owns script tracking via its own changelog, so no __EFMigrationsHistory ceremony is needed.
--
-- The shape MUST match what the platform model produces. Source of truth:
--   Platform.ReliableMessaging.Outbox.EFCore.OutboxMessageConfiguration (table/columns/comments)
--   + EFCore.NamingConventions snake_case convention on OutboxDbContext (column casing).
-- Columns are snake_case; the table name is the literal OutboxRelay:TableName (outbox_messages),
-- the schema is the literal OutboxRelay:SchemaName (benchmark) — both supplied by BenchmarkFixture.

DO $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname = 'benchmark') THEN
        CREATE SCHEMA benchmark;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS benchmark.outbox_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    topic_name character varying(249) NOT NULL,
    kafka_key character varying(128),
    avro_payload bytea NOT NULL,
    type character varying(255) NOT NULL,
    headers character varying(8192),
    created_utc timestamp with time zone NOT NULL,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (id)
);

COMMENT ON TABLE benchmark.outbox_messages IS 'Outbox pattern table for storing domain events as Avro-serialized messages for reliable event publishing.';
COMMENT ON COLUMN benchmark.outbox_messages.id IS 'PK, Identity';
COMMENT ON COLUMN benchmark.outbox_messages.topic_name IS 'The Kafka topic where this message will be published. Set by the message producer.';
COMMENT ON COLUMN benchmark.outbox_messages.kafka_key IS 'Kafka Key - typically the Aggregate ID for proper event ordering and partitioning';
COMMENT ON COLUMN benchmark.outbox_messages.avro_payload IS 'Avro-serialized domain event payload';
COMMENT ON COLUMN benchmark.outbox_messages.type IS 'Avro type name of the serialized event (e.g., ''FeedbackChangedEvent'') for deserialization and observability';
COMMENT ON COLUMN benchmark.outbox_messages.headers IS 'JSON dictionary of OpenTelemetry-standard headers for distributed tracing and metadata. Headers are automatically generated by OpenTelemetry propagators for end-to-end trace context propagation.';
COMMENT ON COLUMN benchmark.outbox_messages.created_utc IS 'Creation timestamp (UTC).';
