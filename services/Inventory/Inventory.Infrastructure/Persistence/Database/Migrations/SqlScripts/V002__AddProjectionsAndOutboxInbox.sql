    IF NOT EXISTS(SELECT 1 FROM inventory."__EFMigrationsHistory" WHERE "migration_id" = '20260425111658_AddProjectionsAndOutboxInbox') THEN
    CREATE TABLE inventory.current_stock_levels (
        product_id uuid NOT NULL,
        on_hand integer NOT NULL,
        reserved integer NOT NULL,
        available integer NOT NULL,
        previous_available integer NOT NULL,
