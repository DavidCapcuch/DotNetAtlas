    COMMENT ON COLUMN inventory.current_stock_levels.on_hand IS 'Physical units present after the last applied event.';
    COMMENT ON COLUMN inventory.current_stock_levels.reserved IS 'Active reservations total after the last applied event.';
    COMMENT ON COLUMN inventory.current_stock_levels.available IS 'OnHand - Reserved after the last applied event. Materialised for indexable reads.';
    COMMENT ON COLUMN inventory.current_stock_levels.previous_available IS 'Available BEFORE the last applied event; enables StockLevelChanged threshold detection without state replay.';
    COMMENT ON COLUMN inventory.current_stock_levels.last_updated_utc IS '= OccurredOnUtc of the last applied event.';
    COMMENT ON COLUMN inventory.current_stock_levels.last_version IS 'Monotonic per-stream event count applied to this row — guards future projection rebuilds against duplicates.';
    END IF;
END $EF$;

