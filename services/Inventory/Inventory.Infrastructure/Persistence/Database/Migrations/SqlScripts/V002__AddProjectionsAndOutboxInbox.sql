    COMMENT ON COLUMN inventory.reservation_audit.product_id IS 'Stream id joining back to inventory.current_stock_levels.ProductId.';
    COMMENT ON COLUMN inventory.reservation_audit.order_id IS 'Owning order. Fan-in key for saga correlation.';
    COMMENT ON COLUMN inventory.reservation_audit.quantity IS 'Units reserved. Immutable after the initial insert.';
    COMMENT ON COLUMN inventory.reservation_audit.status IS 'Lifecycle: Active -> Confirmed | Released.';
    COMMENT ON COLUMN inventory.reservation_audit.reserved_at_utc IS 'UTC timestamp the reservation was created.';
    COMMENT ON COLUMN inventory.reservation_audit.expires_at_utc IS 'UTC expiry (= ReservedAtUtc + TTL). Drives the TTL worker scan.';
    COMMENT ON COLUMN inventory.reservation_audit.resolved_at_utc IS 'UTC timestamp of the terminal transition; null while Active.';
    COMMENT ON COLUMN inventory.reservation_audit.release_reason IS 'Populated only on Status=Released (Compensation | Expiry | Cancellation).';
    END IF;
