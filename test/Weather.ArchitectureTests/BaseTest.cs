using System.Reflection;
using DotNetAtlas.Test.Framework.Kafka;
using Mono.Cecil;
using Mono.Cecil.Rocks;
using NetArchTest.Rules;
using Weather.Api.Common;
using Weather.Application.Common;
using Weather.Domain.Alerts.Events;
using Weather.Infrastructure.Common;

namespace Weather.ArchitectureTests;

public abstract class BaseTest
{
    protected static readonly Assembly DomainAssembly = typeof(SubscriptionExtendedDomainEvent).Assembly;
    protected static readonly Assembly ApplicationAssembly = typeof(ApplicationDependencyInjection).Assembly;
    protected static readonly Assembly InfrastructureAssembly = typeof(InfrastructureDependencyInjection).Assembly;
    protected static readonly Assembly PresentationAssembly = typeof(ApiDependencyInjection).Assembly;

    protected static readonly Assembly TestFrameworkAssembly = typeof(KafkaTestContainer).Assembly;

    protected sealed class PrivateConstructorsRule : ICustomRule
    {
        public bool MeetsRule(TypeDefinition type)
        {
            foreach (var constructor in type.GetConstructors())
            {
                // exclude autogenerated static ctor for private static fields like Regex etc.
                if (!constructor.IsStatic && !constructor.IsPrivate)
                {
                    return false;
                }
            }

            return true;
        }
    }
}
